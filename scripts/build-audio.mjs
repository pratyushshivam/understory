// Turns the full-length field recordings listed in audio/sources.json into the short clips
// the page plays, and writes the credits that go with them.
//
//   node scripts/build-audio.mjs            (needs ffmpeg and curl on the PATH)
//
// For each recording it downloads the original from xeno-canto into raw/ (not committed),
// finds the loudest stretch of the stated length, starts the cut in the quiet just before it,
// removes rumble below the animal's voice, gently reduces tape hiss, sets the peak level,
// and saves a mono 64 kbit/s MP3 in public/audio/. Nothing is pitch-shifted, sped up or mixed.

import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sources = JSON.parse(readFileSync(join(root, 'audio/sources.json'), 'utf8'));
mkdirSync(join(root, 'raw'), { recursive: true });
mkdirSync(join(root, 'public/audio'), { recursive: true });

const LOW_VOICES = new Set(['red-howler', 'great-potoo', 'crested-owl', 'spectacled-owl', 'screech-owl', 'smoky-jungle-frog', 'cane-toad', 'gladiator-treefrog']);
const RATE = 22050;
const HOP = Math.round(RATE * 0.05);

const rows = [];
for (const s of sources) {
  const id = s.xc.replace('XC', '');
  const raw = join(root, 'raw', `${s.xc}.mp3`);
  if (!existsSync(raw) || statSync(raw).size < 1000) {
    console.log('downloading', s.xc);
    execFileSync('curl', ['-sL', '-m', '120', '-o', raw, `https://xeno-canto.org/${id}/download`]);
  }
  const pcm = spawnSync('ffmpeg', ['-v', 'error', '-i', raw, '-ac', '1', '-ar', String(RATE), '-af', 'highpass=f=200', '-f', 'f32le', '-'], {
    maxBuffer: 1 << 30,
  }).stdout;
  const data = new Float32Array(pcm.buffer, pcm.byteOffset, Math.floor(pcm.byteLength / 4));
  const hops = Math.floor(data.length / HOP);
  const energy = new Float64Array(hops);
  for (let h = 0; h < hops; h++) {
    let e = 0;
    for (let i = h * HOP; i < (h + 1) * HOP; i++) e += data[i] * data[i];
    energy[h] = e / HOP;
  }
  const want = Math.min(hops, Math.round(s.seconds / 0.05));
  let best = 0;
  let bestE = -1;
  let run = 0;
  for (let h = 0; h < hops; h++) {
    run += energy[h];
    if (h >= want) run -= energy[h - want];
    if (h >= want - 1 && run > bestE) {
      bestE = run;
      best = h - want + 1;
    }
  }
  // Step back to the quiet before the first call in the window, up to 1.5 s.
  const mean = bestE / want;
  let start = best;
  for (let h = best; h > Math.max(0, best - 30); h--) {
    if (energy[h] < mean * 0.06) {
      start = h;
      break;
    }
  }
  const startS = Math.max(0, start * 0.05 - 0.1);
  const dur = Math.min(s.seconds + (best - start) * 0.05 + 0.6, data.length / RATE - startS);
  let peak = 0;
  for (let i = Math.floor(startS * RATE); i < Math.min(data.length, Math.floor((startS + dur) * RATE)); i++) peak = Math.max(peak, Math.abs(data[i]));
  const gainDb = 20 * Math.log10(0.8 / Math.max(peak, 1e-4));
  const hp = LOW_VOICES.has(s.species) ? 110 : 280;
  const file = `${s.species}.mp3`;
  const out = join(root, 'public/audio', file);
  const filter = [
    `highpass=f=${hp}`,
    'afftdn=nr=10:nf=-42',
    `volume=${gainDb.toFixed(1)}dB`,
    'afade=t=in:d=0.06',
    `afade=t=out:st=${(dur - 0.5).toFixed(2)}:d=0.5`,
    'alimiter=limit=0.9',
  ].join(',');
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-ss', startS.toFixed(2), '-t', dur.toFixed(2), '-i', raw, '-af', filter, '-ac', '1', '-ar', '44100', '-c:a', 'libmp3lame', '-b:a', '64k', '-map_metadata', '-1', out]);
  const kb = Math.round(statSync(out).size / 1024);
  console.log(`${s.species.padEnd(26)} ${s.xc.padEnd(10)} ${startS.toFixed(1).padStart(6)}s +${dur.toFixed(1)}s  ${kb} KB`);
  rows.push({ ...s, file, from: startS, length: dur, kb });
}

const credit = (r) => `${r.recordist}, xeno-canto ${r.xc}, ${r.licence}`;
writeFileSync(
  join(root, 'src/core/recordings.ts'),
  `// Generated by scripts/build-audio.mjs from audio/sources.json. Do not edit by hand.
// One real recording per species, trimmed and re-encoded; full credits are in CREDITS.md.

export type Recording = { file: string; credit: string };

export const RECORDINGS: Record<string, Recording> = {
${rows.map((r) => `  '${r.species}': { file: '${r.file}', credit: ${JSON.stringify(credit(r))} },`).join('\n')}
};
`,
);

const table = rows
  .map(
    (r) =>
      `| ${r.scientific} | [${r.xc}](${r.page}) | ${r.recordist} | ${r.location ? r.location.replace(/\|/g, '/') + ', ' : ''}${r.country} | [${r.licence}](${r.licence_url}) | ${r.from.toFixed(1)} s to ${(r.from + r.length).toFixed(1)} s | ${r.note || ''} |`,
  )
  .join('\n');
writeFileSync(
  join(root, 'audio/credits-table.md'),
  `| Species | Recording | Recordist | Where | Licence | Part used | Note |\n| --- | --- | --- | --- | --- | --- | --- |\n${table}\n`,
);
console.log(`\n${rows.length} clips, ${rows.reduce((a, r) => a + r.kb, 0)} KB in total`);
